# GripRehab project clean-up (approved list 2026-11-21; generated graph, old MCP backup, pip/npm caches and an unused-entry
# prune of the uv cache added 2026-11-23). Deletes PERMANENTLY; nothing here is used by the game, the
# build or the tests. Run from anywhere with Unity and the game closed:
#   powershell -ExecutionPolicy Bypass -File E:\GP\codex\GripRehab-Unity\Tools\release\Cleanup-Project.ps1
# Kept: Library, Builds, Tools/AI packages, models, ai-engine/.venv-ai, .venv, .local tools, the latest release, the
# demo video, and the two real Hand Lab recordings (bridge.jsonl, game.csv, session.json, report.*).
param([switch]$DryRun) # -DryRun lists what would go and deletes nothing
$ErrorActionPreference = 'Continue'
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
Set-Location $root
# Everything it does is also written to cleanup-log.txt in the project folder (2026-11-23: a run that showed nothing).
Start-Transcript -Path (Join-Path $root 'cleanup-log.txt') -Force | Out-Null
Write-Host "GripRehab cleanup started $(Get-Date). Do not click inside this window (that pauses it); press Esc if you did."
$step = 0
function Remove-CleanupItem($p) { if ($DryRun) { Write-Host "  (dry run) would delete $p" } else { Remove-Item $p -Recurse -Force -ErrorAction Continue } }
function Step($text) { $script:step++; Write-Host ""; Write-Host "[$script:step/7] $text" }

$paths = @(
  'Logs\recovery', 'Logs\ai-2026-10-22', 'Logs\ReferenceProof', 'Logs\item1-runtime-fixture', 'Logs\activity-shots',
  'Logs\hand-lab\synthetic-selftest',
  'ai-engine\.venv-ai-old', '.venv-old', '.venv-cv',
  'CVTraining\datasets', 'CVTraining\runs', 'CVTraining\cache',
  'firmware\.arduino-data', 'firmware\.arduino-downloads', 'firmware\.tools', 'firmware\.build',
  '.local\scratch', 'graphify-out', '.mcp.json.bak', '.local\cache\pip', '.local\cache\npm',
  # Unity's package download cache (2.5 GB): the project's packages are already in Library; Unity downloads into it again
  # only if Library is rebuilt (needs the internet then). Added 2026-11-23.
  '.local\cache\unity-upm'
)
Step "Old outputs, environments and caches (several minutes)"
foreach ($p in $paths) { if (Test-Path $p) { Write-Host "Deleting $p"; Remove-CleanupItem $p } }

Step 'Hand Lab replays'
# Hand Lab replays (re-creatable from the recordings).
Get-ChildItem 'Logs\hand-lab' -Directory -ErrorAction SilentlyContinue | ForEach-Object {
  Get-ChildItem $_.FullName -Directory -Filter 'replay-*' | ForEach-Object { Write-Host "Deleting $($_.FullName)"; Remove-CleanupItem $_.FullName }
}
Step 'Old logs'
# Old loose log files and folders in Logs (not hand-lab); logs are regenerated by every run.
Get-ChildItem 'Logs' -Force -ErrorAction SilentlyContinue | Where-Object { $_.Name -ne 'hand-lab' } | ForEach-Object { Remove-CleanupItem $_.FullName }

Step 'Old releases (the newest stays)'
# Old releases: everything except the newest ($keep) and the demo video. Only once the newest exists, so a release always stays.
$keep = '1.3.0'
if (Test-Path ".local\release\GripRehab-$keep") {
  Get-ChildItem '.local\release' -Force -ErrorAction SilentlyContinue |
    Where-Object { $_.Name -match '^GripRehab-(Setup-)?\d+\.\d+\.\d+' -and $_.Name -notmatch [regex]::Escape($keep) -and $_.Name -notmatch 'demo' } |
    ForEach-Object { Write-Host "Deleting $($_.FullName)"; Remove-CleanupItem $_.FullName }
} else { Write-Host "Release $keep not built yet: old releases kept" }
Step 'Python caches'
# Caches.
Get-ChildItem -Path $root -Recurse -Force -Directory -ErrorAction SilentlyContinue -Include '__pycache__', '.pytest_cache' |
  Where-Object { $_.FullName -notmatch '\\(Library|\.venv|ai-engine\\\.venv-ai)\\' } | ForEach-Object { Remove-CleanupItem $_.FullName }

Step 'Unused tool cache entries'
# Tool cache: drop only entries nothing uses (the tools Claude runs, such as Unity MCP, start from this cache: never wiped).
# Skipped while any uv tool runs (Claude's MCP servers): prune would wait for them forever (2026-11-23).
if (-not $DryRun -and (Test-Path '.local\bin\uv.exe') -and -not (Get-Process uv, uvx -ErrorAction SilentlyContinue)) { $env:UV_CACHE_DIR = (Join-Path $root '.local\cache\uv'); & '.local\bin\uv.exe' cache prune }
else { Write-Host 'uv cache prune skipped: uv tools are running (run again with them closed)' }

Step 'Git: pack history, drop old large-file copies (nothing in the history is lost)'
# Pack git's loose objects (keeps all history) and drop old local copies of large files git LFS already has (current ones stay).
if (-not $DryRun) { git gc --quiet; git lfs prune } else { Write-Host '  (dry run) would pack git and prune old LFS copies' }

Write-Host ""
Write-Host "Cleanup finished $(Get-Date). The log is cleanup-log.txt in the project folder."
Stop-Transcript | Out-Null
