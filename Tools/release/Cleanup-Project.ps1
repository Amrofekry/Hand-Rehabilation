# GripRehab project clean-up (approved list, 2026-11-21). Deletes PERMANENTLY; nothing here is used by the game, the
# build or the tests. Run from anywhere with Unity and the game closed:
#   powershell -ExecutionPolicy Bypass -File E:\GP\codex\GripRehab-Unity\Tools\release\Cleanup-Project.ps1
# Kept: Library, Builds, Tools/AI packages, models, ai-engine/.venv-ai, .venv, .local tools, the latest release, the
# demo video, and the two real Hand Lab recordings (bridge.jsonl, game.csv, session.json, report.*).
$ErrorActionPreference = 'Continue'
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
Set-Location $root
function Size($p) { if (Test-Path $p) { [math]::Round(((Get-ChildItem $p -Recurse -Force -File -ErrorAction SilentlyContinue | Measure-Object Length -Sum).Sum) / 1GB, 2) } else { 0 } }
$before = Size $root
Write-Host "Project before: $before GB"

$paths = @(
  'Logs\recovery', 'Logs\ai-2026-10-22', 'Logs\ReferenceProof', 'Logs\item1-runtime-fixture', 'Logs\activity-shots',
  'Logs\hand-lab\synthetic-selftest',
  'ai-engine\.venv-ai-old', '.venv-old', '.venv-cv',
  'CVTraining\datasets', 'CVTraining\runs', 'CVTraining\cache',
  'firmware\.arduino-data', 'firmware\.arduino-downloads', 'firmware\.tools', 'firmware\.build',
  '.local\scratch'
)
foreach ($p in $paths) { if (Test-Path $p) { Write-Host "Deleting $p"; Remove-Item $p -Recurse -Force -ErrorAction Continue } }

# Hand Lab replays (re-creatable from the recordings).
Get-ChildItem 'Logs\hand-lab' -Directory -ErrorAction SilentlyContinue | ForEach-Object {
  Get-ChildItem $_.FullName -Directory -Filter 'replay-*' | ForEach-Object { Write-Host "Deleting $($_.FullName)"; Remove-Item $_.FullName -Recurse -Force }
}
# Old loose log files and folders in Logs (not hand-lab); logs are regenerated by every run.
Get-ChildItem 'Logs' -Force -ErrorAction SilentlyContinue | Where-Object { $_.Name -ne 'hand-lab' } | ForEach-Object { Remove-Item $_.FullName -Recurse -Force -ErrorAction Continue }

# Old releases 1.0.0 - 1.0.7 (the newest release and the demo video stay).
foreach ($v in 0..7) {
  foreach ($p in @(".local\release\GripRehab-1.0.$v", ".local\release\GripRehab-1.0.$v-portable.zip", ".local\release\GripRehab-Setup-1.0.$v.exe")) {
    if (Test-Path $p) { Write-Host "Deleting $p"; Remove-Item $p -Recurse -Force }
  }
}
# Caches.
Get-ChildItem -Path $root -Recurse -Force -Directory -ErrorAction SilentlyContinue -Include '__pycache__', '.pytest_cache' |
  Where-Object { $_.FullName -notmatch '\\(Library|\.venv|ai-engine\\\.venv-ai)\\' } | ForEach-Object { Remove-Item $_.FullName -Recurse -Force -ErrorAction SilentlyContinue }

# Pack git's loose objects (keeps all history).
git gc --quiet

$after = Size $root
Write-Host "Project after: $after GB (freed $([math]::Round($before - $after, 2)) GB)"
